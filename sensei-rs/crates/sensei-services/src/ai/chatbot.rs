/// Configuration for the chatbot service.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatbotConfig {
    /// Optional path to model weights file.
    pub model_path: Option<String>,
    /// Maximum number of tokens to generate per response.
    #[serde(default = "default_max_tokens")]
    pub max_tokens: usize,
    /// Sampling temperature (0.0 = greedy, higher = more random).
    #[serde(default = "default_temperature")]
    pub temperature: f32,
    /// Top-k sampling parameter (0 = disabled).
    #[serde(default = "default_top_k")]
    pub top_k: u32,
    /// Top-p (nucleus) sampling parameter (0.0 = disabled, 1.0 = all).
    #[serde(default = "default_top_p")]
    pub top_p: f32,
    /// System prompt prepended to all conversations.
    #[serde(default = "default_system_prompt")]
    pub system_prompt: String,
}

fn default_max_tokens() -> usize {
    256
}
fn default_temperature() -> f32 {
    0.7
}
fn default_top_k() -> u32 {
    40
}
fn default_top_p() -> f32 {
    0.9
}
fn default_system_prompt() -> String {
    "You are Starz Forge AI, the manufacturing operations assistant of the Starz group. You help users with quality management, maintenance, production, supply chain, finance, HR, and continuous improvement topics.".to_string()
}

impl Default for ChatbotConfig {
    fn default() -> Self {
        Self {
            model_path: None,
            max_tokens: default_max_tokens(),
            temperature: default_temperature(),
            top_k: default_top_k(),
            top_p: default_top_p(),
            system_prompt: default_system_prompt(),
        }
    }
}

/// A single chat message in a conversation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatMessage {
    /// The role of the message sender (e.g., "user", "assistant", "system").
    pub role: String,
    /// The message content.
    pub content: String,
    /// When this message was sent.
    pub timestamp: DateTime<Utc>,
}

impl ChatMessage {
    /// Create a new user message.
    pub fn user(content: String) -> Self {
        Self {
            role: "user".to_string(),
            content,
            timestamp: Utc::now(),
        }
    }

    /// Create a new assistant message.
    pub fn assistant(content: String) -> Self {
        Self {
            role: "assistant".to_string(),
            content,
            timestamp: Utc::now(),
        }
    }

    /// Create a new system message.
    pub fn system(content: String) -> Self {
        Self {
            role: "system".to_string(),
            content,
            timestamp: Utc::now(),
        }
    }
}

/// Response from a chat request.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChatResponse {
    /// The assistant's response message.
    pub message: ChatMessage,
    /// Unique conversation identifier.
    pub conversation_id: String,
    /// Whether this response was generated by the model or fallback.
    pub is_fallback: bool,
}

/// Per-request sampling parameters that override the service defaults.
///
/// `None` fields fall back to the service configuration; providing a field
/// (even `0` for temperature/top-k) overrides it.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct ChatSamplingParams {
    /// Maximum number of tokens to generate.
    pub max_tokens: Option<usize>,
    /// Sampling temperature (0.0 = greedy).
    pub temperature: Option<f32>,
    /// Top-k sampling parameter (0 = disabled).
    pub top_k: Option<u32>,
    /// Top-p (nucleus) sampling parameter.
    pub top_p: Option<f32>,
}

impl ChatSamplingParams {
    /// Effective max tokens for a request (request override or config).
    pub fn max_tokens_or(&self, config: usize) -> usize {
        self.max_tokens.unwrap_or(config)
    }

    /// Effective temperature for a request (request override or config).
    pub fn temperature_or(&self, config: f32) -> f32 {
        self.temperature.unwrap_or(config)
    }

    /// Effective top-k for a request (request override or config).
    pub fn top_k_or(&self, config: u32) -> u32 {
        self.top_k.unwrap_or(config)
    }

    /// Effective top-p for a request (request override or config).
    pub fn top_p_or(&self, config: f32) -> f32 {
        self.top_p.unwrap_or(config)
    }
}

