//! Chatbot service for conversational AI interactions.
//!
//! Provides a [`ChatbotService`] trait with chat and streaming-chat
//! methods, along with an in-memory implementation backed by
//! [`sensei_zt::llm::LlamaRunner`] for LLaMA-based inference or
//! pattern-matching fallback when model weights are unavailable.

