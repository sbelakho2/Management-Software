/// Chatbot service for conversational AI.
///
/// Provides methods for single-turn chat, streaming chat, and
/// conversation history retrieval.
#[async_trait]
pub trait ChatbotService: Send + Sync {
    /// Send a chat message and receive a response.
    ///
    /// `tenant_id` identifies the tenant/organisation.
    /// `user_id` identifies the user sending the message.
    /// `message` is the user's input text.
    /// `conversation_id` optionally specifies an existing conversation
    /// to continue. If `None`, a new conversation is started.
    /// `sampling` optionally overrides the configured sampling parameters
    /// (max tokens, temperature, top-k, top-p) for this request.
    /// `system_context` is the server-built authoritative context bundle
    /// (Context Kernel, sixteenth audit 8/96) threaded into the prompt
    /// BEFORE generation — the model never invents the retrieval strategy.
    async fn chat(
        &self,
        tenant_id: EntityId,
        user_id: EntityId,
        message: &str,
        conversation_id: Option<&str>,
        sampling: Option<ChatSamplingParams>,
        system_context: Option<&str>,
    ) -> Result<ChatResponse>;

    /// Stream a chat response token by token.
    ///
    /// Returns a [`mpsc::Receiver`] that yields result strings, each
    /// representing one token (or a chunk of the response).
    /// `sampling` optionally overrides the configured sampling parameters
    /// for this request.
    async fn stream_chat(
        &self,
        tenant_id: EntityId,
        user_id: EntityId,
        message: &str,
        conversation_id: Option<&str>,
        sampling: Option<ChatSamplingParams>,
    ) -> Result<mpsc::Receiver<Result<String>>>;

    /// Retrieve the full conversation history.
    async fn get_conversation_history(
        &self,
        tenant_id: EntityId,
        conversation_id: &str,
    ) -> Result<Vec<ChatMessage>>;
}

