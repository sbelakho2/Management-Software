/// LLaMA-backed chatbot service using [`sensei_zt::llm::LlamaRunner`].
///
/// When model weights are available, runs the full transformer pipeline
/// via Zig FFI. Otherwise falls back to pattern-matching responses.
pub struct SenseiChatbotService {
    /// The underlying LLaMA runner (wrapped in Mutex for thread safety).
    runner: Arc<Mutex<Option<sensei_zt::llm::LlamaRunner>>>,
    /// Chatbot configuration.
    config: ChatbotConfig,
    /// In-memory conversation store keyed by conversation ID.
    conversation_store: Arc<RwLock<HashMap<String, Vec<ChatMessage>>>>,
}

impl SenseiChatbotService {
    /// Create a new [`SenseiChatbotService`].
    ///
    /// Attempts to load model weights from `config.model_path`. If the
    /// path is `None` or loading fails, falls back to the pure-Rust
    /// pattern-matching chatbot.
    pub fn new(config: ChatbotConfig) -> Self {
        let runner = if let Some(ref path) = config.model_path {
            // Attempt to load weights from file
            match std::fs::read(path) {
                Ok(bytes) => {
                    // Interpret bytes as f32 weights
                    let weight_count = bytes.len() / 4;
                    let mut weights = vec![0.0f32; weight_count];
                    unsafe {
                        std::ptr::copy_nonoverlapping(
                            bytes.as_ptr(),
                            weights.as_mut_ptr() as *mut u8,
                            bytes.len(),
                        );
                    }

                    let llm_config = sensei_zt::llm::LlamaConfig::default();
                    match sensei_zt::llm::LlamaRunner::new(llm_config, &weights) {
                        Ok(runner) => {
                            tracing::info!("Loaded LLaMA model weights from {path}");
                            Some(runner)
                        }
                        Err(e) => {
                            tracing::warn!(
                                "Failed to initialise LLaMA runner from {path}: {e}. Falling back to pattern matching."
                            );
                            None
                        }
                    }
                }
                Err(e) => {
                    tracing::warn!(
                        "Failed to read model weights from {path}: {e}. Falling back to pattern matching."
                    );
                    None
                }
            }
        } else {
            None
        };

        Self {
            runner: Arc::new(Mutex::new(runner)),
            config,
            conversation_store: Arc::new(RwLock::new(HashMap::new())),
        }
    }

    /// Generate a conversation ID for a new conversation.
    fn generate_conversation_id() -> String {
        uuid::Uuid::new_v4().to_string()
    }

    /// Build the full prompt including system prompt, the authoritative
    /// live context bundle and conversation history.
    fn build_prompt(
        &self,
        message: &str,
        history: &[ChatMessage],
        system_context: Option<&str>,
    ) -> String {
        let mut prompt = String::new();

        // System prompt
        prompt.push_str(&self.config.system_prompt);
        prompt.push('\n');

        // Context Kernel (sixteenth audit 8/96): the authoritative live
        // bundle is part of the prompt — generation happens WITH it, it is
        // not attached afterwards as metadata.
        if let Some(context) = system_context {
            let trimmed = context.trim();
            if !trimmed.is_empty() {
                prompt.push_str("AUTHORITATIVE CONTEXT (live): ");
                prompt.push_str(trimmed);
                prompt.push('\n');
            }
        }

        // Conversation history
        for msg in history {
            prompt.push_str(&format!("{}: {}\n", msg.role, msg.content));
        }

        // Current message
        prompt.push_str(&format!("user: {message}\n"));
        prompt.push_str("assistant: ");

        prompt
    }
}

#[async_trait]
impl ChatbotService for SenseiChatbotService {
    async fn chat(
        &self,
        _tenant_id: EntityId,
        _user_id: EntityId,
        message: &str,
        conversation_id: Option<&str>,
        sampling: Option<ChatSamplingParams>,
        system_context: Option<&str>,
    ) -> Result<ChatResponse> {
        let conv_id = conversation_id
            .map(|s| s.to_string())
            .unwrap_or_else(Self::generate_conversation_id);

        // Get or create conversation history
        let history = {
            let store = self.conversation_store.read().await;
            store.get(&conv_id).cloned().unwrap_or_default()
        };

        // Build prompt
        let prompt = self.build_prompt(message, &history, system_context);

        // Per-request sampling overrides the configured defaults.
        let sampling = sampling.unwrap_or_default();
        let max_tokens = sampling.max_tokens_or(self.config.max_tokens);
        let temperature = sampling.temperature_or(self.config.temperature);
        let top_k = sampling.top_k_or(self.config.top_k);
        let top_p = sampling.top_p_or(self.config.top_p);

        // Generate response
        let mut runner_guard = self.runner.lock().await;
        let (response, is_fallback) = if let Some(ref mut runner) = *runner_guard {
            match runner.generate(&prompt, max_tokens, temperature, top_k, top_p) {
                Ok(resp) => (resp, false),
                Err(e) => {
                    tracing::warn!("LLaMA generation failed: {e}. Falling back.");
                    (fallback_chat(message), true)
                }
            }
        } else {
            (fallback_chat(message), true)
        };

        // Save to conversation history
        {
            let mut store = self.conversation_store.write().await;
            let conv = store.entry(conv_id.clone()).or_default();
            conv.push(ChatMessage::user(message.to_string()));
            conv.push(ChatMessage::assistant(response.clone()));
        }

        Ok(ChatResponse {
            message: ChatMessage::assistant(response),
            conversation_id: conv_id,
            is_fallback,
        })
    }

    async fn stream_chat(
        &self,
        tenant_id: EntityId,
        user_id: EntityId,
        message: &str,
        conversation_id: Option<&str>,
        sampling: Option<ChatSamplingParams>,
    ) -> Result<mpsc::Receiver<Result<String>>> {
        let (tx, rx) = mpsc::channel::<Result<String>>(64);

        let this = self.clone();
        let message = message.to_string();
        let conv_id = conversation_id
            .map(|s| s.to_string())
            .unwrap_or_else(Self::generate_conversation_id);

        tokio::spawn(async move {
            // Get the full response first
            let response = this
                .chat(tenant_id, user_id, &message, Some(&conv_id), sampling, None)
                .await;

            match response {
                Ok(chat_resp) => {
                    // Stream tokens word by word
                    for word in chat_resp.message.content.split(' ') {
                        if tx.send(Ok(format!("{word} "))).await.is_err() {
                            break;
                        }
                        tokio::time::sleep(std::time::Duration::from_millis(20)).await;
                    }
                }
                Err(e) => {
                    let _ = tx.send(Err(e)).await;
                }
            }
        });

        Ok(rx)
    }

    async fn get_conversation_history(
        &self,
        _tenant_id: EntityId,
        conversation_id: &str,
    ) -> Result<Vec<ChatMessage>> {
        let store = self.conversation_store.read().await;
        store.get(conversation_id).cloned().ok_or_else(|| {
            SenseiError::NotFound(format!("Conversation {conversation_id} not found"))
        })
    }
}

impl Clone for SenseiChatbotService {
    fn clone(&self) -> Self {
        Self {
            runner: Arc::clone(&self.runner),
            config: self.config.clone(),
            conversation_store: Arc::clone(&self.conversation_store),
        }
    }
}

