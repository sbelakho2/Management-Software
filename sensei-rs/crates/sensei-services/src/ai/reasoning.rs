/// Analyzes closed A3 reports to identify patterns, compute countermeasure
/// correlations, and suggest effective countermeasures.
pub struct A3PatternAnalyzer {
    /// Maximum number of closed A3 reports to retain.
    max_history: usize,
    /// Closed A3 reports indexed by ID.
    closed_a3s: HashMap<Uuid, A3Report>,
    /// Cache of computed countermeasure correlations.
    correlations: Vec<CountermeasureCorrelation>,
    /// Cache of category → success rate.
    success_rates: HashMap<String, f64>,
    /// Whether the correlation cache is stale.
    correlations_dirty: bool,
}

impl A3PatternAnalyzer {
    /// Create a new [`A3PatternAnalyzer`] with the given history limit.
    pub fn new(max_history: usize) -> Self {
        Self {
            max_history,
            closed_a3s: HashMap::new(),
            correlations: Vec::new(),
            success_rates: HashMap::new(),
            correlations_dirty: false,
        }
    }

    /// Register a closed A3 report for pattern analysis.
    ///
    /// If the history exceeds `max_history`, the oldest 25 % are evicted.
    pub fn add_closed_a3(&mut self, a3: A3Report) {
        self.closed_a3s.insert(a3.id, a3);
        self.correlations_dirty = true;
        self.evict_cache_if_needed();
    }

    /// Remove the oldest 25 % of A3 reports when history exceeds the limit.
    fn evict_cache_if_needed(&mut self) {
        if self.closed_a3s.len() <= self.max_history {
            return;
        }

        let mut entries: Vec<(DateTime<Utc>, Uuid)> = self
            .closed_a3s
            .values()
            .map(|a3| (a3.closed_at, a3.id))
            .collect();
        entries.sort_by(|a, b| a.0.cmp(&b.0));

        let to_remove = self.max_history / 4;
        for (_, id) in entries.iter().take(to_remove) {
            self.closed_a3s.remove(id);
        }
        self.correlations_dirty = true;
    }

    /// Compute the improvement for each KPI in an A3 report.
    fn calculate_kpi_improvements(a3: &A3Report) -> HashMap<String, f64> {
        a3.kpis
            .iter()
            .map(|kpi| {
                let improvement = if kpi.baseline_value != 0.0 {
                    (kpi.current_value - kpi.baseline_value) / kpi.baseline_value
                } else {
                    kpi.current_value
                };
                (kpi.name.clone(), improvement)
            })
            .collect()
    }

    /// (Re)compute countermeasure correlations from all closed A3s.
    fn compute_correlations(&mut self) {
        if !self.correlations_dirty && !self.correlations.is_empty() {
            return;
        }

        // Collect category → improvements for each applied countermeasure
        let mut category_improvements: HashMap<String, Vec<f64>> = HashMap::new();
        let mut category_count: HashMap<String, usize> = HashMap::new();

        for a3 in self.closed_a3s.values() {
            let improvements = Self::calculate_kpi_improvements(a3);
            let avg_improvement: f64 = if improvements.is_empty() {
                0.0
            } else {
                improvements.values().sum::<f64>() / improvements.len() as f64
            };

            for cm in &a3.countermeasures {
                category_improvements
                    .entry(cm.category.clone())
                    .or_default()
                    .push(avg_improvement);
                *category_count.entry(cm.category.clone()).or_insert(0) += 1;
            }
        }

        let mut correlations = Vec::new();
        let mut success_rates = HashMap::new();

        for (category, improvements) in &category_improvements {
            let sample_size = improvements.len();
            let avg_improvement = improvements.iter().sum::<f64>() / sample_size as f64;
            // "Success" = improvement > 5 %
            let successes = improvements.iter().filter(|&&v| v > 0.05).count();
            let success_rate = successes as f64 / sample_size as f64;
            let applied_count = *category_count.get(category).unwrap_or(&0);

            correlations.push(CountermeasureCorrelation {
                category: category.clone(),
                avg_improvement,
                sample_size,
                success_rate,
                applied_count,
            });
            success_rates.insert(category.clone(), success_rate);
        }

        // Sort by success rate descending
        correlations.sort_by(|a, b| b.success_rate.partial_cmp(&a.success_rate).unwrap_or(std::cmp::Ordering::Equal));

        self.correlations = correlations;
        self.success_rates = success_rates;
        self.correlations_dirty = false;
    }

    /// Suggest countermeasures for a given waste category, sorted by
    /// historical success rate.
    pub fn suggest_countermeasures(&mut self, waste_category: &str) -> Vec<CountermeasureCorrelation> {
        self.compute_correlations();
        // Filter and return correlations that match the waste category
        // (or return all if no specific matches)
        let mut matches: Vec<CountermeasureCorrelation> = self
            .correlations
            .iter()
            .filter(|c| {
                c.category.to_lowercase().contains(&waste_category.to_lowercase())
            })
            .cloned()
            .collect();

        if matches.is_empty() {
            // Return top 3 overall suggestions
            matches = self.correlations.iter().take(3).cloned().collect();
        }

        matches
    }

    /// Get the historical success rate for a countermeasure category.
    pub fn get_success_rate(&mut self, category: &str) -> f64 {
        self.compute_correlations();
        self.success_rates
            .get(category)
            .copied()
            .unwrap_or(0.5) // default 50 % if unknown
    }

    /// Get statistics about the pattern analysis.
    pub fn get_stats(&self) -> HashMap<String, serde_json::Value> {
        let mut stats = HashMap::new();
        stats.insert(
            "total_a3s_analyzed".to_string(),
            serde_json::Value::Number(serde_json::Number::from(self.closed_a3s.len() as u64)),
        );
        stats.insert(
            "correlations_cached".to_string(),
            serde_json::Value::Number(serde_json::Number::from(self.correlations.len() as u64)),
        );
        stats
    }

    /// Export the internal state as a serializable value.
    pub fn export_state(&self) -> HashMap<String, serde_json::Value> {
        let mut state = HashMap::new();
        state.insert(
            "closed_a3_count".to_string(),
            serde_json::Value::Number(serde_json::Number::from(self.closed_a3s.len() as u64)),
        );
        state
    }

    /// Get a reference to all correlations.
    pub fn correlations(&self) -> &[CountermeasureCorrelation] {
        &self.correlations
    }
}

impl Default for A3PatternAnalyzer {
    fn default() -> Self {
        Self::new(1000)
    }
}

