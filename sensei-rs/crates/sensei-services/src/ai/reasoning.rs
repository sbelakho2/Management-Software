/// Unified reasoning engine that orchestrates A3 analysis, Socratic mentoring,
/// and 5 Whys root cause analysis.
pub struct SenseiReasoningEngine {
    pub pattern_analyzer: A3PatternAnalyzer,
    pub socratic_mentor: SocraticMentor,
    pub five_whys: FiveWhysAssistant,
}

impl SenseiReasoningEngine {
    /// Create a new [`SenseiReasoningEngine`].
    pub fn new() -> Self {
        Self {
            pattern_analyzer: A3PatternAnalyzer::default(),
            socratic_mentor: SocraticMentor::default(),
            five_whys: FiveWhysAssistant::default(),
        }
    }

    /// Register a closed A3 report for pattern analysis.
    pub fn register_closed_a3(&mut self, a3: A3Report) {
        self.pattern_analyzer.add_closed_a3(a3);
    }

    /// Suggest countermeasures for a waste category.
    pub fn suggest_countermeasures(
        &mut self,
        waste_category: &str,
    ) -> Vec<CountermeasureCorrelation> {
        self.pattern_analyzer.suggest_countermeasures(waste_category)
    }

    /// Generate challenging prompts for a session.
    pub fn generate_socratic_prompts(
        &mut self,
        session_id: &str,
        content: &str,
        persona: MentorPersona,
        phase: A3Phase,
    ) -> Vec<ChallengingPrompt> {
        self.socratic_mentor
            .generate_prompts_for_session(session_id, content, persona, phase)
    }

    /// Analyze root cause using 5 Whys.
    pub fn analyze_root_cause(&mut self, problem: &str) -> Vec<RootCauseSuggestion> {
        self.five_whys.analyze_problem(problem)
    }

    /// Classify waste category from text.
    pub fn classify_waste(&self, text: &str) -> Option<LeanWasteCategory> {
        self.five_whys.classify_waste(text)
    }

    /// Classify muda type from text.
    pub fn classify_muda_type(&self, text: &str) -> Option<MudaType> {
        self.five_whys.classify_muda_type(text)
    }

    /// Start a Socratic mentoring session.
    pub fn start_mentoring_session(&mut self, session_id: &str, a3_id: &str) {
        self.socratic_mentor.start_session(session_id, a3_id);
    }

    /// End a mentoring session.
    pub fn end_mentoring_session(&mut self, session_id: &str) -> HashMap<String, serde_json::Value> {
        self.socratic_mentor.end_session(session_id)
    }

    /// Get engine statistics.
    pub fn get_stats(&self) -> HashMap<String, serde_json::Value> {
        let mut stats = self.pattern_analyzer.get_stats();
        stats.insert(
            "five_whys_historical_causes".to_string(),
            serde_json::Value::Number(serde_json::Number::from(
                self.five_whys.historical_causes.len() as u64,
            )),
        );
        stats
    }
}

impl Default for SenseiReasoningEngine {
    fn default() -> Self {
        Self::new()
    }
}

