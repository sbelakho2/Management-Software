//! AI Reasoning Engine — A3 Pattern Analysis, Socratic Mentoring, and 5 Whys.
//!
//! Ported from [`reasoning_engine.py`](backend/src/sensei/services/ai/reasoning_engine.py).
//!
//! # Components
//!
//! - [`A3PatternAnalyzer`] — Analyzes closed A3 reports, computes countermeasure
//!   correlations, and suggests countermeasures based on historical success rates.
//! - [`SocraticMentor`] — Generates Socratic/challenging prompts for mentoring
//!   sessions, adapting to different mentor personas and A3 phases.
//! - [`FiveWhysAssistant`] — Performs 5-Whys root cause analysis, classifies waste
//!   categories, and identifies muda types using keyword-based pattern matching.
//! - [`SenseiReasoningEngine`] — Orchestrates the three assistants and provides a
//!   unified public API.

