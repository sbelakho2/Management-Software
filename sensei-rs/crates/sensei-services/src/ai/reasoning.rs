/// Generates Socratic/challenging prompts for mentoring sessions.
///
/// Adapts prompts based on the mentor persona and the current A3 phase.
pub struct SocraticMentor {
    /// Maximum session history entries to retain.
    max_history: usize,
    /// Conversation history per session.
    session_history: HashMap<String, Vec<ChallengingPrompt>>,
    /// Active sessions — maps session_id to (a3_id, start_time).
    active_sessions: HashMap<String, (String, DateTime<Utc>)>,
}

impl SocraticMentor {
    /// Create a new [`SocraticMentor`] with the given history limit.
    pub fn new(max_history: usize) -> Self {
        Self {
            max_history,
            session_history: HashMap::new(),
            active_sessions: HashMap::new(),
        }
    }

    /// Generate challenging prompts for a given content, persona, and phase.
    ///
    /// Prompts are stored in the history under a key derived from the content
    /// (used when no session is active). Prefer
    /// [`SocraticMentor::generate_prompts_for_session`] for session-scoped use.
    pub fn generate_prompts(
        &mut self,
        content: &str,
        persona: MentorPersona,
        phase: A3Phase,
    ) -> Vec<ChallengingPrompt> {
        let prompts = self.build_prompts(content, persona, phase);

        // Track in session history (keyed by a synthetic session key derived from content)
        let session_key = self.extract_key_terms(content).join("_");
        self.session_history
            .entry(session_key)
            .or_default()
            .extend(prompts.clone());

        self.evict_cache_if_needed();

        prompts
    }

    /// Generate challenging prompts for an explicit mentoring session.
    ///
    /// The prompts are recorded under `session_id` so that
    /// [`SocraticMentor::end_session`] and
    /// [`SocraticMentor::get_session_history`] report real per-session stats.
    pub fn generate_prompts_for_session(
        &mut self,
        session_id: &str,
        content: &str,
        persona: MentorPersona,
        phase: A3Phase,
    ) -> Vec<ChallengingPrompt> {
        // Auto-register the session if it was never started.
        if !self.active_sessions.contains_key(session_id) {
            self.active_sessions
                .insert(session_id.to_string(), (String::new(), Utc::now()));
        }

        let prompts = self.build_prompts(content, persona, phase);
        self.session_history
            .entry(session_id.to_string())
            .or_default()
            .extend(prompts.clone());

        self.evict_cache_if_needed();

        prompts
    }

    /// Build the prompt list for the given content without touching history.
    fn build_prompts(
        &self,
        content: &str,
        persona: MentorPersona,
        phase: A3Phase,
    ) -> Vec<ChallengingPrompt> {
        let focused_types = phase_focus(phase);
        let mut prompts = Vec::new();

        for &prompt_type in focused_types {
            let templates = prompt_templates(persona, prompt_type);
            if templates.is_empty() {
                continue;
            }

            let mut rng = rand::thread_rng();
            let idx = rng.gen_range(0..templates.len());
            let chosen = templates[idx];

            // Check if content contains keywords related to this prompt type
            let aspect = self.identify_aspect(content);
            let follow_ups = self.get_follow_ups(prompt_type);

            let prompt = ChallengingPrompt {
                id: Uuid::new_v4(),
                prompt_type,
                content: format!("{} (Ref: {})", chosen, aspect),
                persona,
                phase,
                follow_ups: follow_ups.into_iter().map(|s| s.to_string()).collect(),
                created_at: Utc::now(),
            };

            prompts.push(prompt);
        }

        prompts
    }

    /// Extract key terms from content (simplified — splits on whitespace and
    /// returns unique, non-trivial words).
    fn extract_key_terms(&self, content: &str) -> Vec<String> {
        let stop_words = [
            "the", "a", "an", "is", "are", "was", "were", "be", "been",
            "have", "has", "had", "do", "does", "did", "will", "would",
            "could", "should", "may", "might", "shall", "can", "need",
            "this", "that", "these", "those", "it", "its", "they", "them",
            "their", "we", "us", "our", "you", "your", "he", "she", "his",
            "her", "and", "or", "but", "not", "no", "nor", "so", "if",
            "then", "else", "when", "where", "why", "how", "what", "which",
            "who", "whom", "to", "of", "in", "for", "on", "with", "at",
            "by", "from", "as", "into", "through", "during", "before",
            "after", "above", "below", "between", "out", "off", "over",
            "under", "again", "further", "once",
        ];

        content
            .split(|c: char| !c.is_alphanumeric())
            .filter(|w| w.len() >= 3)
            .map(|w| w.to_lowercase())
            .filter(|w| !stop_words.contains(&w.as_str()))
            .collect()
    }

    /// Identify the aspect of the content (simplified keyword-based).
    fn identify_aspect(&self, content: &str) -> String {
        let lower = content.to_lowercase();
        if lower.contains("defect") || lower.contains("quality") {
            "Quality Issue".to_string()
        } else if lower.contains("delay") || lower.contains("wait") || lower.contains("time") {
            "Timing / Delay".to_string()
        } else if lower.contains("cost") || lower.contains("budget") || lower.contains("expense") {
            "Cost Concern".to_string()
        } else if lower.contains("process") || lower.contains("procedure") || lower.contains("step") {
            "Process Related".to_string()
        } else if lower.contains("people") || lower.contains("team") || lower.contains("training") {
            "People / Skills".to_string()
        } else {
            "General".to_string()
        }
    }

    /// Get follow-up prompts for a given prompt type.
    fn get_follow_ups(&self, prompt_type: PromptType) -> &'static [&'static str] {
        use PromptType::*;
        match prompt_type {
            Exploration => &[
                "Tell me more about that.",
                "What else have you observed?",
                "Can you elaborate on that point?",
            ],
            Reflection => &[
                "How does this compare to past experiences?",
                "What would you do differently next time?",
                "What lessons can you draw from this?",
            ],
            Assumption => &[
                "Why do you believe that is true?",
                "What if the opposite were true?",
                "How could you test that assumption?",
            ],
            Evidence => &[
                "What data supports that claim?",
                "How was that measurement taken?",
                "Can you show me the source?",
            ],
            ActionPlanning => &[
                "What's your first step?",
                "Who needs to be involved?",
                "What could go wrong and how will you mitigate it?",
            ],
            Perspective => &[
                "How would other stakeholders view this?",
                "What's the broader impact?",
                "Consider the long-term implications.",
            ],
        }
    }

    /// Start a mentoring session.
    pub fn start_session(&mut self, session_id: &str, a3_id: &str) {
        self.active_sessions
            .insert(session_id.to_string(), (a3_id.to_string(), Utc::now()));
        // A new session starts with an empty conversation history so per-session
        // stats reflect only this session's prompts.
        self.session_history.remove(session_id);
    }

    /// End a mentoring session and return session statistics.
    pub fn end_session(&mut self, session_id: &str) -> HashMap<String, serde_json::Value> {
        let mut stats = HashMap::new();
        if let Some((_a3_id, start_time)) = self.active_sessions.remove(session_id) {
            let duration = Utc::now() - start_time;
            let duration_minutes = duration.num_minutes();
            let history = self.session_history.get(session_id).map_or(0, |v| v.len());

            stats.insert(
                "session_duration_minutes".to_string(),
                serde_json::Value::Number(serde_json::Number::from(duration_minutes.max(0) as u64)),
            );
            stats.insert(
                "prompts_generated".to_string(),
                serde_json::Value::Number(serde_json::Number::from(history as u64)),
            );
        } else {
            stats.insert(
                "error".to_string(),
                serde_json::Value::String("Session not found".to_string()),
            );
        }
        stats
    }

    /// Evict the oldest 25 % of session histories when the limit is exceeded.
    fn evict_cache_if_needed(&mut self) {
        let total: usize = self.session_history.values().map(|v| v.len()).sum();
        if total <= self.max_history {
            return;
        }

        // Simple eviction: clear everything beyond max_history
        let mut all_entries: Vec<(String, ChallengingPrompt)> = self
            .session_history
            .iter()
            .flat_map(|(key, prompts)| {
                prompts.iter().map(|p| (key.clone(), p.clone()))
            })
            .collect();

        all_entries.sort_by(|a, b| a.1.created_at.cmp(&b.1.created_at));

        let target = self.max_history * 3 / 4; // keep 75 %
        let to_remove = all_entries.len().saturating_sub(target);

        self.session_history.clear();
        for (key, prompt) in all_entries.into_iter().skip(to_remove) {
            self.session_history.entry(key).or_default().push(prompt);
        }
    }

    /// Get the conversation history for a session.
    pub fn get_session_history(&self, session_id: &str) -> Vec<ChallengingPrompt> {
        self.session_history
            .get(session_id)
            .cloned()
            .unwrap_or_default()
    }

    /// Export internal state.
    pub fn export_state(&self) -> HashMap<String, serde_json::Value> {
        let mut state = HashMap::new();
        state.insert(
            "active_sessions".to_string(),
            serde_json::Value::Number(serde_json::Number::from(self.active_sessions.len() as u64)),
        );
        state.insert(
            "total_history".to_string(),
            serde_json::Value::Number(serde_json::Number::from(
                self.session_history.values().map(|v| v.len()).sum::<usize>() as u64,
            )),
        );
        state
    }
}

impl Default for SocraticMentor {
    fn default() -> Self {
        Self::new(5000)
    }
}

