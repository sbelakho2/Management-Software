/// A single KPI measurement.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct KPIMetric {
    pub name: String,
    pub current_value: f64,
    pub target_value: f64,
    pub baseline_value: f64,
    pub unit: String,
    pub trend: KPITrend,
    pub measured_at: DateTime<Utc>,
}

impl KPIMetric {
    /// Returns `true` if the current value meets or exceeds the target.
    pub fn is_on_target(&self) -> bool {
        if self.current_value >= self.target_value {
            true
        } else {
            // Allow 5 % tolerance below target
            let tolerance = self.target_value * 0.05;
            (self.target_value - self.current_value).abs() <= tolerance
        }
    }
}

