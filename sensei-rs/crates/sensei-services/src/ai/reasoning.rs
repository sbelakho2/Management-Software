/// Performs 5-Whys root cause analysis and waste classification.
///
/// Uses keyword-based pattern matching to identify waste categories, muda
/// types, and potential root causes from problem descriptions.
#[allow(dead_code)]
pub struct FiveWhysAssistant {
    /// Maximum number of historical cause entries.
    max_history: usize,
    /// Historical (problem, cause) pairs.
    historical_causes: Vec<(String, String)>,
    /// Maximum historical entries before eviction.
    max_historical_causes: usize,
}

impl FiveWhysAssistant {
    /// Create a new [`FiveWhysAssistant`].
    pub fn new(max_history: usize) -> Self {
        Self {
            max_history,
            historical_causes: Vec::new(),
            max_historical_causes: 5000,
        }
    }

    /// Analyze a problem description using the 5 Whys method.
    ///
    /// Returns a list of [`RootCauseSuggestion`] items sorted by pattern
    /// match score (highest first).
    pub fn analyze_problem(&mut self, problem: &str) -> Vec<RootCauseSuggestion> {
        let patterns = root_cause_patterns();
        let mut suggestions: Vec<(f64, RootCauseSuggestion)> = patterns
            .iter()
            .map(|pattern| {
                let score = self.calculate_pattern_match(problem, pattern.pattern);
                if score > 0.0 {
                    let (waste, muda) = self.classify_from_text(problem);
                    (
                        score,
                        RootCauseSuggestion {
                            cause: pattern.category.to_string(),
                            pattern_match_score: score,
                            evidence_needed: pattern
                                .evidence_questions
                                .iter()
                                .map(|s| s.to_string())
                                .collect(),
                            related_waste: waste,
                            related_muda: muda,
                        },
                    )
                } else {
                    (0.0, RootCauseSuggestion {
                        cause: pattern.category.to_string(),
                        pattern_match_score: 0.0,
                        evidence_needed: Vec::new(),
                        related_waste: None,
                        related_muda: None,
                    })
                }
            })
            .filter(|(score, _)| *score > 0.0)
            .collect();

        // Sort by score descending
        suggestions.sort_by(|a, b| {
            b.0.partial_cmp(&a.0).unwrap_or(std::cmp::Ordering::Equal)
        });

        let result: Vec<RootCauseSuggestion> = suggestions
            .into_iter()
            .map(|(_, s)| s)
            .collect();

        // Store in historical causes
        if let Some(best) = result.first() {
            self.add_historical_cause(problem, &best.cause);
        }

        result
    }

    /// Calculate pattern match score based on keyword density.
    fn calculate_pattern_match(&self, text: &str, pattern: &str) -> f64 {
        let lower = text.to_lowercase();
        let keywords: Vec<&str> = pattern.split('|').collect();
        if keywords.is_empty() {
            return 0.0;
        }

        let total_words = text.split_whitespace().count();
        if total_words == 0 {
            return 0.0;
        }

        let matches: usize = keywords
            .iter()
            .filter(|kw| lower.contains(*kw))
            .count();

        // Score = (matches / total_keywords) * coverage_factor
        let ratio = matches as f64 / keywords.len() as f64;
        let coverage = ratio.min(1.0);
        coverage
    }

    /// Classify waste category and muda type from text.
    fn classify_from_text(&self, text: &str) -> (Option<LeanWasteCategory>, Option<MudaType>) {
        let waste = self.classify_waste(text);
        let muda = self.classify_muda_type(text);
        (waste, muda)
    }

    /// Classify the lean waste category based on keyword matching.
    pub fn classify_waste(&self, text: &str) -> Option<LeanWasteCategory> {
        let lower = text.to_lowercase();
        let mut best_category = None;
        let mut best_score = 0.0f64;

        for (category, keywords) in waste_keywords() {
            let matches: usize = keywords
                .iter()
                .filter(|kw| lower.contains(*kw))
                .count();
            let score = matches as f64 / keywords.len() as f64;

            if score > best_score {
                best_score = score;
                best_category = Some(category);
            }
        }

        best_category.filter(|_| best_score > 0.05)
    }

    /// Classify the muda type based on keyword matching.
    pub fn classify_muda_type(&self, text: &str) -> Option<MudaType> {
        let lower = text.to_lowercase();
        let mut best_type = None;
        let mut best_score = 0.0f64;

        for (muda_type, keywords) in muda_keywords() {
            let matches: usize = keywords
                .iter()
                .filter(|kw| lower.contains(*kw))
                .count();
            let score = matches as f64 / keywords.len() as f64;

            if score > best_score {
                best_score = score;
                best_type = Some(muda_type);
            }
        }

        best_type.filter(|_| best_score > 0.05)
    }

    /// Find similar historical causes.
    pub fn find_similar_historical(&self, pattern: &str) -> Vec<String> {
        let lower_pattern = pattern.to_lowercase();
        let mut matches: Vec<(usize, &str)> = self
            .historical_causes
            .iter()
            .filter_map(|(problem, cause)| {
                if problem.to_lowercase().contains(&lower_pattern) {
                    Some((0, cause.as_str()))
                } else {
                    // Simple word overlap
                    let pattern_words: Vec<&str> = lower_pattern
                        .split_whitespace()
                        .filter(|w| w.len() > 3)
                        .collect();
                    let overlap: usize = pattern_words
                        .iter()
                        .filter(|w| problem.to_lowercase().contains(*w))
                        .count();
                    if overlap > 0 {
                        Some((overlap, cause.as_str()))
                    } else {
                        None
                    }
                }
            })
            .collect();

        matches.sort_by(|a, b| b.0.cmp(&a.0));
        matches.dedup_by(|a, b| a.1 == b.1);

        matches.into_iter().take(5).map(|(_, s)| s.to_string()).collect()
    }

    /// Get evidence needs for a given pattern.
    pub fn get_evidence_needs(&self, pattern: &str) -> Vec<String> {
        let patterns = root_cause_patterns();
        for p in &patterns {
            let lower_pattern = pattern.to_lowercase();
            let keywords: Vec<&str> = p.pattern.split('|').collect();
            if keywords.iter().any(|kw| lower_pattern.contains(kw)) {
                return p.evidence_questions.iter().map(|s| s.to_string()).collect();
            }
        }
        vec![
            "What data supports this finding?".to_string(),
            "Can you verify this through direct observation?".to_string(),
            "What measurements confirm this analysis?".to_string(),
        ]
    }

    /// Add a historical cause entry.
    pub fn add_historical_cause(&mut self, problem: &str, cause: &str) {
        self.historical_causes
            .push((problem.to_string(), cause.to_string()));

        if self.historical_causes.len() > self.max_historical_causes {
            let to_remove = self.max_historical_causes / 4;
            self.historical_causes.drain(..to_remove);
        }
    }

    /// Get a summary of waste categories found in the historical data.
    pub fn get_waste_summary(&self) -> Vec<(LeanWasteCategory, usize)> {
        let mut counts: HashMap<LeanWasteCategory, usize> = HashMap::new();
        for (problem, _) in &self.historical_causes {
            if let Some(waste) = self.classify_waste(problem) {
                *counts.entry(waste).or_insert(0) += 1;
            }
        }

        let mut result: Vec<(LeanWasteCategory, usize)> = counts.into_iter().collect();
        result.sort_by(|a, b| b.1.cmp(&a.1));
        result
    }

    /// Export state.
    pub fn export_state(&self) -> HashMap<String, serde_json::Value> {
        let mut state = HashMap::new();
        state.insert(
            "historical_causes_count".to_string(),
            serde_json::Value::Number(serde_json::Number::from(self.historical_causes.len() as u64)),
        );
        state
    }
}

impl Default for FiveWhysAssistant {
    fn default() -> Self {
        Self::new(5000)
    }
}

