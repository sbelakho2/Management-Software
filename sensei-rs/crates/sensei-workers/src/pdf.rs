#[cfg(test)]
mod tests {
    use super::*;

    fn a3_payload() -> PdfTaskPayload {
        PdfTaskPayload {
            kind: PdfKind::A3,
            data: serde_json::json!({
                "id": "A3-20260824-0001",
                "title": "Defect rate too high",
                "problem_statement": "PPM rose from 500 to 4200",
                "current_state": "Current state description",
                "goal": "Reduce PPM below 1000",
                "root_cause_analysis": "Lack of calibration",
                "countermeasures": "Weekly calibration",
                "check_plan": "Weekly audit",
                "follow_up": "Review in 30 days",
                "owner": "Quality Manager",
                "status": "active",
                "created_at": "2026-08-24",
            }),
        }
    }

    #[test]
    fn test_a3_payload_deserializes_into_document_data() {
        let payload = a3_payload();
        let a3: A3Data = serde_json::from_value(payload.data).expect("valid A3 data");
        assert_eq!(a3.title, "Defect rate too high");
        assert_eq!(a3.id, "A3-20260824-0001");
    }

    #[test]
    fn test_missing_a3_data_fails_clearly() {
        let payload = PdfTaskPayload {
            kind: PdfKind::A3,
            data: serde_json::json!({"id": "only-id"}),
        };
        let err = serde_json::from_value::<A3Data>(payload.data).unwrap_err();
        assert!(err.to_string().contains("title"), "error: {err}");
    }

    #[test]
    fn test_pdf_export_service_generates_a3_bytes() {
        let a3: A3Data = serde_json::from_value(a3_payload().data).unwrap();
        let pdf = PdfExportService::new();
        let bytes = pdf.generate_a3_report(&a3).expect("A3 PDF generation");
        assert!(!bytes.is_empty());
        // PDF magic header.
        assert_eq!(&bytes[..5], b"%PDF-");
    }

    #[test]
    fn test_pdf_export_service_generates_quote_bytes() {
        let quote = QuoteData {
            id: "Q-1".into(),
            quote_number: "QTE-20260824-0001".into(),
            customer_name: "Acme Corp".into(),
            date: "2026-08-24".into(),
            valid_until: "2026-09-24".into(),
            currency: "USD".into(),
            line_items: vec![sensei_services::export::pdf::QuoteLineData {
                description: "CNC Housing".into(),
                quantity: "50".into(),
                unit_price: "45.00".into(),
                total: "2250.00".into(),
            }],
            subtotal: "2250.00".into(),
            tax: "450.00".into(),
            total: "2700.00".into(),
        };
        let pdf = PdfExportService::new();
        let bytes = pdf.generate_quote(&quote).expect("quote PDF generation");
        assert!(!bytes.is_empty());
        assert_eq!(&bytes[..5], b"%PDF-");
    }
}
